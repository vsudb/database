WITH test_data (id, value) AS (
VALUES (1, 'A'),
       (2, 'B'),
       (3, NULL),
       (4, 'A'),
       (5, NULL))
SELECT
	COUNT(*) AS cnt_all,                    -- Результат: 5 (все строки)
    COUNT(value) AS cnt_val_without_null,   -- Результат: 3 (только не-NULL)
    COUNT(DISTINCT value) AS cnt_distinct   -- Результат: 2 (A, B)
FROM test_data;

